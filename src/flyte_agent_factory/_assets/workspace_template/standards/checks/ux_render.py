"""Render the declared pages in a real browser and check what a person would hit.

Per page and viewport it saves a full-page screenshot to ux-evidence/ and reports console errors, failed
requests, horizontal overflow and text cut off at the right edge (at the smallest declared viewport, and at
any 320px or narrower), text contrast (again in the dark colour scheme when the page styles one), images
without alt, controls without an accessible name, a missing title or lang, and too-small touch targets (24px,
or 44px when the audience includes children under 13). For an audience that includes people 65 or over it also
reports running text under 16px. At the largest viewport only it also presses Tab through the page and reports
controls (native ones and ARIA widgets) Tab never reaches and focused elements whose look does not change.
Open shadow roots and same-origin frames count as part of the page. ux-evidence/report.json has every finding,
and what could not be measured.

Not measured, and printed as such: text over images or gradients, text under filters or blend modes, text
generated by ::before or ::after content, closed shadow roots, cross-origin frames, text drawn in images,
canvas or video, and console errors later than about a second after the network goes quiet.

Time budget: the factory kills a check at 300s. Finding Playwright takes at most NPM_SECONDS, the serve
command READY_SECONDS to answer and rendering NODE_SECONDS, 270s in all; past RENDER_BUDGET_SECONDS of
rendering, pages not yet rendered are reported as not rendered rather than the run being cut off.

Exit 0: pass, or NOT APPLICABLE (no pages: nothing human-facing, or only text or a CLI). Exit 1: findings
(or a page that cannot be rendered). Exit 127: node, Playwright or Chromium is missing or broken (an image
defect, not the project's fault). Run from the project directory.
Playwright is looked for in the project's node_modules, in NODE_PATH, then in the npm global root, including
the @playwright/mcp bundle; Chromium comes from PLAYWRIGHT_BROWSERS_PATH (or /ms-playwright when that exists).
"""

import contextlib
import json
import os
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from collections.abc import Iterator
from pathlib import Path
from typing import Any

# The standards directory is not the project's: importing a sibling must not leave __pycache__ in it.
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import _ux_common as common  # type: ignore[import-not-found]  # noqa: E402 -- this directory is put on sys.path above

OUT_DIR = "ux-evidence"
NPM_SECONDS = 10
READY_SECONDS = 60
NODE_SECONDS = 200
# The node script stops starting pages this long before NODE_SECONDS, so it can still write what it found.
RENDER_BUDGET_SECONDS = NODE_SECONDS - 25
SHOWN = 10
FALLBACK_GLOBAL_ROOT = "/usr/local/lib/node_modules"
EXIT_NO_TOOL = 127
# The node script's own exit code for Playwright or the browser not loading.
NODE_NO_TOOL = 3
# Limits of the method, printed with every result so a pass is not read as covering them.
ALWAYS_UNMEASURED = [
    "closed shadow roots and cross-origin frames (their content cannot be reached from the page)",
    "text drawn inside images, canvas or video",
    "console errors later than about 1s after the network goes quiet",
]

# Runs the serve command and kills its whole process group when its stdin closes. The check holds the other
# end of that pipe, so the server goes when the check does, even when the check itself is killed with SIGKILL
# (as the factory does at its timeout) and no cleanup code of ours runs. A plain process group would outlive
# it: it has to be a new session for us to kill the server's children, and then nothing kills it for us.
WATCHDOG = """
import os, signal, subprocess, sys, threading
server = subprocess.Popen(sys.argv[1], shell=True, stdin=subprocess.DEVNULL)
def watch():
    sys.stdin.buffer.read()
    os.killpg(0, signal.SIGKILL)
threading.Thread(target=watch, daemon=True).start()
sys.exit(server.wait())
"""


def find_playwright(root: Path) -> Path | None:
    """Return the directory of a Playwright package: the project's, then NODE_PATH, then npm's global root."""
    candidates = [root / "node_modules" / "playwright"]
    candidates += [Path(p) / "playwright" for p in os.environ.get("NODE_PATH", "").split(os.pathsep) if p]
    found = next((c for c in candidates if (c / "package.json").is_file()), None)
    if found:
        return found
    global_roots = []
    npm = shutil.which("npm")
    if npm:
        try:
            out = subprocess.run([npm, "root", "-g"], capture_output=True, text=True, timeout=NPM_SECONDS)
            if out.returncode == 0 and out.stdout.strip():
                global_roots.append(out.stdout.strip())
        except (OSError, subprocess.TimeoutExpired):
            pass
    global_roots.append(FALLBACK_GLOBAL_ROOT)
    for base in global_roots:
        candidates += [Path(base) / "playwright", Path(base) / "@playwright/mcp/node_modules/playwright"]
    return next((c for c in candidates if (c / "package.json").is_file()), None)


def find_tools(root: Path) -> tuple[str, Path] | str:
    """Return (node, Playwright directory), or why they cannot be used."""
    node = shutil.which("node")
    if not node:
        return "node is not on PATH"
    playwright = find_playwright(root)
    if not playwright:
        return "Playwright is not installed (looked in node_modules, NODE_PATH and the npm global root)"
    return node, playwright


class ToolUnavailable(Exception):
    """Node, Playwright or Chromium is missing or broken: an image defect, not the project's fault."""


def resolve_page_url(root: Path, page: str) -> tuple[str, str]:
    """Return (url, name) for a declared page: URLs as they are, project files as file:// URLs."""
    if re.match(r"https?://", page):
        return page, re.sub(r"^https?://", "", page)
    return (root / page).resolve().as_uri(), page


def wait_ready(url: str, server: subprocess.Popen[bytes]) -> str:
    """Poll `url` until it answers (any HTTP status) or READY_SECONDS pass; return "" or the reason."""
    deadline = time.monotonic() + READY_SECONDS
    while time.monotonic() < deadline:
        if server.poll() is not None:
            return f"the serve command exited with {server.returncode} before {url} answered"
        try:
            urllib.request.urlopen(url, timeout=5).close()
            return ""
        except urllib.error.HTTPError:
            return ""  # it answered
        except (urllib.error.URLError, OSError):
            time.sleep(0.5)
    return f"{url} did not answer within {READY_SECONDS}s of starting the serve command"


def _exit_on_signal(signum: int, _frame: Any) -> None:
    raise SystemExit(128 + signum)


@contextlib.contextmanager
def serve_project(root: Path, surfaces: dict[str, Any]) -> Iterator[str]:
    """Run surfaces.serve, if any, for the duration; yield "" once surfaces.ready answers, or the problem."""
    serve = surfaces.get("serve")
    if not serve:
        yield ""
        return
    # SIGTERM and SIGHUP would end Python without running `finally`; turned into SystemExit, they do run it.
    for signum in (signal.SIGTERM, signal.SIGHUP):
        signal.signal(signum, _exit_on_signal)
    server = subprocess.Popen(
        [sys.executable, "-c", WATCHDOG, serve], cwd=root, start_new_session=True,
        stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )  # fmt: skip
    try:
        yield wait_ready(surfaces["ready"], server)
    finally:
        assert server.stdin is not None
        server.stdin.close()
        with contextlib.suppress(ProcessLookupError):
            os.killpg(server.pid, signal.SIGKILL)
        server.wait()


def run_node(node: str, playwright: Path, root: Path, config: dict[str, Any]) -> tuple[int, str]:
    """Run the node script with `config` (it writes config["out"]); return (exit code, its output)."""
    env = dict(os.environ, UX_PLAYWRIGHT_DIR=str(playwright))
    if "PLAYWRIGHT_BROWSERS_PATH" not in env and Path("/ms-playwright").is_dir():
        env["PLAYWRIGHT_BROWSERS_PATH"] = "/ms-playwright"
    with tempfile.TemporaryDirectory() as tmp:
        config_file = Path(tmp, "config.json")
        config_file.write_text(json.dumps({"budgetSeconds": RENDER_BUDGET_SECONDS, **config}))
        script = Path(__file__).with_suffix(".mjs")
        try:
            done = subprocess.run(
                [node, str(script), str(config_file)],
                cwd=root, env=env, capture_output=True, text=True, timeout=NODE_SECONDS,
            )  # fmt: skip
        except subprocess.TimeoutExpired:
            return 1, f"rendering took longer than {NODE_SECONDS}s"
    return done.returncode, (done.stdout + done.stderr).strip()


def get_rendered_text(
    root: Path, surfaces: dict[str, Any], pages: list[str], viewport: str
) -> tuple[dict[str, list[str] | str], str]:
    """Render `pages` and return ({page: text blocks, or why it failed}, ""), or ({}, why nothing rendered).

    For the reading-level check: the text a reader sees, including what scripts insert.
    Raises ToolUnavailable, naming the missing tool, when there is no browser to render with.
    """
    tools = find_tools(root)
    if isinstance(tools, str):
        raise ToolUnavailable(tools)
    with serve_project(root, surfaces) as problem, tempfile.TemporaryDirectory() as tmp:
        if problem:
            return {}, problem
        out = Path(tmp, "text.json")
        config: dict[str, Any] = {"mode": "text", "pages": [], "viewport": viewport, "out": str(out)}
        config["pages"] = [{"url": u, "name": p} for p in pages for u, _ in [resolve_page_url(root, p)]]
        code, output = run_node(*tools, root, config)
        if code == NODE_NO_TOOL:
            raise ToolUnavailable(output)
        if code != 0:
            return {}, (output.splitlines() or [f"the render script exited with {code}"])[-1]
        data = json.loads(out.read_text())
    return {p["name"]: p.get("blocks", p.get("error", "")) for p in data["pages"]}, ""


def write_report(
    results: list[dict[str, Any]],
    screenshots: list[str],
    keyboard_viewport: str,
    reflow_widths: list[int],
    dark_pages: list[str] | None = None,
) -> int:
    """Print the per page@viewport summary; return the exit code."""
    total = 0
    unmeasured: dict[str, set[str]] = {}
    for result in results:
        findings = result["findings"]
        total += len(findings)
        for item in result["unmeasured"]:
            # Contrast items say so; a cross-origin frame's reason covers every check inside it.
            reason = f"{item['what']}: {item['reason']}" if item.get("what") else item["reason"]
            unmeasured.setdefault(reason, set()).add(f"{result['page']}: {item['selector']}")
        label = f"{result['page']}@{result['viewport']}"
        if not findings:
            print(f"ok    {label}")
            continue
        kinds: dict[str, int] = {}
        for f in findings:
            kinds[f["kind"]] = kinds.get(f["kind"], 0) + 1
        print(f"FAIL  {label}: {len(findings)} findings ({', '.join(f'{k} {n}' for k, n in kinds.items())})")
        for f in findings[:SHOWN]:
            where = f" {f['selector']}:" if f["selector"] else ""
            print(f"  [{f['kind']}]{where} {f['message']}")
        if len(findings) > SHOWN:
            print(f"  ... {len(findings) - SHOWN} more in {OUT_DIR}/report.json")
    if unmeasured:
        print("Not measured on these pages (judge them in the screenshots; all are in report.json):")
        for reason, places in sorted(unmeasured.items()):
            listed = sorted(places)
            more = f" and {len(listed) - 3} more" if len(listed) > 3 else ""
            print(f"  - {reason}: {', '.join(listed[:3])}{more}")
    print("Not measured on any page: " + "; ".join(ALWAYS_UNMEASURED))
    if dark_pages:
        print(f"Contrast was also checked in the dark colour scheme for: {', '.join(dark_pages)}")
    widths = ", ".join(f"{w}px" for w in reflow_widths)
    narrow = (
        "" if min(reflow_widths) <= 320 else "; WCAG 1.4.10 asks for 320px, so declare a 320x640 viewport"
    )
    print(f"Reflow (no horizontal scrolling) was checked at {widths} wide{narrow}")
    print(f"Keyboard reach and visible focus were checked at the largest viewport only ({keyboard_viewport})")
    print(f"Evidence: {len(screenshots)} screenshots and report.json in {OUT_DIR}/")
    print(f"{'FAIL' if total else 'PASS'}: {total} findings")
    return 1 if total else 0


def main() -> int:
    """Run the check in the current directory."""
    root = Path.cwd()
    config, parse_error = common.load_config(root)
    common.exit_if_malformed(config, root)
    if not common.has_surface(root, config):
        common.exit_not_applicable("no human-facing surface")
    pages = common.get_declared_pages(config)
    if not pages and not common.find_ui_files(root):
        common.exit_not_applicable(
            "no pages to render: no [surfaces] pages and no UI files (a text or CLI product is checked by "
            "the reading-level and walkthrough scripts)"
        )
    if not pages:
        print(f"FAIL: the project has UI files but declares no pages to render. {parse_error}".rstrip())
        print('Add to product.toml:\n[surfaces]\npages = ["path/to/index.html"]   # or http(s) URLs')
        return 1
    surfaces = common.get_surfaces_table(config)
    viewports = surfaces.get("viewports") or common.DEFAULT_VIEWPORTS
    missing = [p for p in pages if not re.match(r"https?://", p) and not (root / p).is_file()]
    if missing:
        print("FAIL: declared pages that do not exist: " + ", ".join(missing))
        return 1
    out_dir = root / OUT_DIR
    escaped = common.find_outside_problem(root, out_dir, str(OUT_DIR))
    if escaped:
        print(f"FAIL: {escaped}")
        return 1

    tools = find_tools(root)
    if isinstance(tools, str):
        print(f"{tools}; cannot render pages")
        return EXIT_NO_TOOL
    with serve_project(root, surfaces) as problem:
        if problem:
            print(f"FAIL: {problem}")
            return 1
        config_out = {
            "pages": [{"url": u, "name": n} for u, n in (resolve_page_url(root, p) for p in pages)],
            "viewports": viewports,
            "under13": common.serves_under_13(config),
            "olderAdults": common.serves_older_adults(config),
            "outDir": str(out_dir),
            "out": str(out_dir / "report.json"),
        }
        code, output = run_node(*tools, root, config_out)
    if code == NODE_NO_TOOL:
        print(output)
        return EXIT_NO_TOOL
    if code != 0:
        print(f"FAIL: the render script failed (exit {code}):\n{output[-2000:]}")
        return 1
    data = json.loads((out_dir / "report.json").read_text())
    return write_report(
        data["results"],
        data["screenshots"],
        data["keyboardViewport"],
        data["reflowWidths"],
        data["darkPages"],
    )


if __name__ == "__main__":
    sys.exit(main())
